/** 过滤（浏览面板的搜索框）：名字 + 朝向（"90" 也能搜到） */
export function filterPoses(list: PosePreset[], q: string): PosePreset[] {
  const kw = q.trim().toLowerCase()
  if (!kw) return list
  return list.filter((x) => x.name.toLowerCase().includes(kw)
    || String(x.yaw).includes(kw))
}

/** 给「存成 XXX」算一个不撞名的名字（XXX / XXX 2 / XXX 3 …）。 */
export function uniquePoseName(list: PosePreset[], base: string): string {
  const b = base.trim()
  if (!list.some((x) => x.name === b)) return b
  for (let i = 2; i < 1000; i++) {
    const cand = `${b} ${i}`
    if (!list.some((x) => x.name === cand)) return cand
  }
  return `${b} ${Date.now()}`
}

/**
 * 读出 localStorage 里的旧存档（**只看不删**）。
 *
 * 迁移要发一次网络请求，失败了数据还得留在浏览器里等下次重试；删由
 * store/legacy.ts 在服务端确认收到之后统一做。
 */
export function readLegacyPoses(): PosePreset[] {
  try {
    const raw = localStorage.getItem(LEGACY_KEY)
    if (!raw) return []
    const arr = JSON.parse(raw)
    if (!Array.isArray(arr)) return []
    return arr
      .filter((x) => x && typeof x.name === 'string' && x.pose
        && typeof x.pose === 'object')
      .slice(0, MAX_POSES)
      .map((x) => ({
        id: String(x.id || x.name),
        name: String(x.name).trim() || '未命名',
        pose: x.pose as unknown,
        yaw: Number(x.yaw) || 0,
        preview: typeof x.preview === 'string' ? x.preview : '',
        at: Number(x.at) || 0,
      }))
  } catch {
    return []
  }
}
